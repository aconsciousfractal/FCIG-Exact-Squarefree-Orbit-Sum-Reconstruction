#!/usr/bin/env python3
"""Independent reconstruction checker for the canonical four-action payload.

The checker deliberately uses a different data path from the producer:
groups are generated by closure from generators, coordinate supports are
scanned by integer weight, and orbit-sum values are accumulated by enumerating
the support subsets contained in each pattern.  No producer module is imported
and no producer-generated separator mask is trusted.
"""

